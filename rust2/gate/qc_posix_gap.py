#!/usr/bin/env python3
"""gate/qc_posix_gap.py — POSIX-spelling gap census for the differential gate (#1488).

The gate corpus (gate/cases/, generated by gen-cases.py) exercises 40+
wired commands almost exclusively through Windows-form or relative path
operands. The product contract is that rubash hands POSIX spellings
verbatim to its applets (niubash#346; the mapper is
src/utils/native_path.cppm:shell_tree_map_w, being ported to
winux-core/path.rs on the P lane) — so every filesystem-touching case is a
missing POSIX variant until a POSIX-spelled twin exists.

This tool produces the acceptance baseline:

1. Static census — classify every case operand's path shape
   (posix-namespace / posix-drive-form / windows-abs / relative / bare)
   per command, count how many cases are filesystem-touching, and how many
   lack a POSIX-spelled variant. Writes gate/POSIX-GAP.md.
2. --fixture-run — run every corpus case's rust side twice: with and
   without the shell-namespace fixture env (__RUBASH_SHELL_ROOT/TMPDIR/HOME,
   see qc_common.posix_fixture). The corpus contains no POSIX spellings, so
   NOTHING may change; any diff is fixture leakage, reported separately.
   This is the "run the corpus under posix-mode" regression leg: it proves
   the fixture itself is inert, so post-port greens on cases-posix/ can be
   attributed to the port.

Run:
    python gate/qc_posix_gap.py                 # static census -> POSIX-GAP.md
    python gate/qc_posix_gap.py --fixture-run   # + inertness leg (native only)
Requires RUST_BIN when the worktree default is not built.
"""

import argparse
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import qc_common as q  # noqa: E402

OUT = os.path.join(q.GATE_DIR, "POSIX-GAP.md")

# Commands whose operands reach the filesystem, by role. Commands absent
# from every list are value/string-model commands with no path operand
# (whoami, uname, seq, od, tr, ...) — they need no POSIX variant.
FS_PRIMARY = {
    # paths ARE the contract; landing assertions meaningful
    "mkdir", "rmdir", "touch", "chmod", "chown", "stat", "realpath",
    "readlink", "ln", "unlink", "truncate", "mktemp", "tee", "sync", "df",
}
FS_FILE_OPERAND = {
    # stdin-primary, GNU accepts file operands — POSIX variants apply
    "head", "tail", "cut", "fold", "paste", "join", "tsort", "tac", "fmt",
    "expand", "unexpand", "base64", "base32", "b2sum", "sha224sum",
    "sha384sum", "sum", "nice", "timeout", "hostname",  # hostname -F <file>
}
FS_TEST = {"test", "bracket"}          # -e/-d/-f/-x path probes
STRING_ONLY = {"basename", "dirname"}  # POSIX spellings are pure strings

# namespace mounts the C++ shell_tree_map_w recognizes (plus bare /-root)
NS_PREFIXES = ("tmp", "var", "home", "mnt", "dev", "usr", "etc", "opt",
               "proc", "bin", "sbin", "lib", "run", "srv")

WINDOWS_ABS = re.compile(r"^([A-Za-z]:[\\/]|[\\/]{2}|\\)")
DRIVE_FORM = re.compile(r"^/[A-Za-z](/|$)")
POSIX_ABS = re.compile(r"^/")


def path_shape(tok):
    """Classify one token's path shape (or None when it has no path shape)."""
    if WINDOWS_ABS.match(tok):
        return "windows-abs"
    if DRIVE_FORM.match(tok):
        return "posix-drive-form"
    if POSIX_ABS.match(tok):
        first = tok[1:].split("/", 1)[0]
        return "posix-ns" if first in NS_PREFIXES else "posix-root"
    if "/" in tok or "\\" in tok:
        return "relative"
    # bare operand: a path only for FS-touching commands (decided by caller)
    return "bare"


def case_shapes(case, cmd):
    """All operand shapes of one case (args + setup + stdin tokens)."""
    toks = list(case.args) + case.setup.replace(";", " ").split()
    if case.stdin:
        toks.append(case.stdin)
    shapes = []
    for t in toks:
        s = path_shape(t)
        if s == "bare":
            # a bare token counts as a path operand only where operands
            # actually reach the filesystem
            if cmd in FS_PRIMARY or cmd in FS_FILE_OPERAND or cmd in FS_TEST:
                s = "bare-operand"
            else:
                continue
        shapes.append(s)
    return shapes


def fs_touching(shapes):
    return bool(shapes)


def census():
    commands = q.list_commands()
    posix_cmds = set(q.list_posix_commands())
    rows = []
    total = posix_shaped = fs_cases = gap_cases = 0
    for cmd in commands:
        cases = q.parse_cases(cmd)
        n = len(cases)
        with_shape = 0
        with_posix = 0
        fs_n = 0
        gap_n = 0
        for c in cases:
            shapes = case_shapes(c, cmd)
            if not shapes:
                continue
            with_shape += 1
            if any(s.startswith("posix") for s in shapes):
                with_posix += 1
            if cmd in STRING_ONLY:
                # string spellings exercise no mapper; count, no gap
                continue
            fs_n += 1
            if not any(s.startswith("posix") for s in shapes):
                gap_n += 1
        total += n
        posix_shaped += with_posix
        fs_cases += fs_n
        gap_cases += gap_n
        cls = ("FS-primary" if cmd in FS_PRIMARY else
               "FS-file-operand" if cmd in FS_FILE_OPERAND else
               "FS-test" if cmd in FS_TEST else
               "string-only" if cmd in STRING_ONLY else "no-path")
        rows.append((cmd, n, with_shape, with_posix, fs_n, gap_n, cls,
                     "yes" if cmd in posix_cmds else "-"))
    return rows, total, posix_shaped, fs_cases, gap_cases


def fixture_run():
    """Run every corpus case's rust side with and without the fixture env."""
    fixture = q.posix_fixture()
    exe = q.rust_bin()
    if not os.path.isfile(exe):
        print("rust driver missing: %s" % exe)
        return None
    sensitive = []
    n = 0
    for cmd in q.list_commands():
        for case in q.parse_cases(cmd):
            n += 1
            sdir = os.path.join(q.QC_ART, "posix-gap", "scratch", cmd, case.cid)
            base = _spawn(exe, cmd, case, {}, sdir)
            with_fx = _spawn(exe, cmd, case, fixture, sdir)
            if (base[0], base[1]) != (with_fx[0], with_fx[1]):
                sensitive.append((cmd, case.cid, base, with_fx))
                print("FIXTURE-SENSITIVE %s/%s rc %s->%s out %r->%r" % (
                    cmd, case.cid, base[0], with_fx[0],
                    base[1][:40], with_fx[1][:40]))
        print("fixture-run: %s done (%d cases, %d sensitive)"
              % (cmd, n, len(sensitive)), file=sys.stderr)
    return n, sensitive


def _spawn(exe, cmd, case, extra_env, sdir):
    """One native rust-side spawn (argv verbatim; no conversion layer).

    Both variants of a case share ONE scratch PATH, wiped between runs:
    cwd-printing commands (pwd, realpath, readlink) would otherwise diff
    by scratch-path asymmetry, while sharing files would diff by state
    leakage (a second `mkdir d` fails on an existing dir).
    """
    import shutil
    if os.path.isdir(sdir):
        shutil.rmtree(sdir)
    os.makedirs(sdir, exist_ok=True)
    env = dict(os.environ)
    env.update(extra_env)
    try:
        p = subprocess.run(
            [exe, cmd] + case.args,
            cwd=sdir,
            input=case.stdin.encode("utf-8"),
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=q.SIDE_TIMEOUT,
            env=env,
        )
        return p.returncode, p.stdout
    except subprocess.TimeoutExpired:
        return None, b""


def write_report(rows, total, posix_shaped, fs_cases, gap_cases, fx):
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        w = fh.write
        w("# POSIX-spelling gap census — POSIX-GAP.md\n\n")
        w("Generated by `python gate/qc_posix_gap.py` over `gate/cases/`.\n")
        w("Acceptance baseline for the shell-namespace round (#1488 gate\n")
        w("posix round): the corpus must grow POSIX-spelled twins for every\n")
        w("filesystem-touching case once the native_path Rust port\n")
        w("(`winux-core/path.rs`, the P lane) lands; the skeletons in\n")
        w("`gate/cases-posix/` go green on the same landing.\n\n")
        w("Contract under test: rubash hands applets POSIX spellings\n")
        w("verbatim (niubash#346); `native_path.cppm:shell_tree_map_w`\n")
        w("resolves /tmp, /var/tmp, /home, /mnt/X, bare-/ root and\n")
        w("/usr/bin exe-folds. Probe-channel rules: gate/PROBE-METHODOLOGY.md.\n\n")
        w("## Corpus census\n\n")
        w("| command | cases | path-shaped | posix-spelled | FS-touching | missing posix variant | class | cases-posix skeleton |\n")
        w("|---|---|---|---|---|---|---|---|\n")
        for (cmd, n, ws, wp, fs, gap, cls, skel) in rows:
            w("| %s | %d | %d | %d | %d | %d | %s | %s |\n"
              % (cmd, n, ws, wp, fs, gap, cls, skel))
        w("| **total** | **%d** | **%d** | **%d** | **%d** | **%d** | | %d tables |\n"
          % (total, sum(r[2] for r in rows), posix_shaped, fs_cases, gap_cases,
             len(posix_cmds_tbl(rows))))
        w("\nReading: *path-shaped* = the case carries at least one operand\n")
        w("with a recognizable path shape; *posix-spelled* = at least one\n")
        w("operand is a POSIX absolute spelling; *missing posix variant* =\n")
        w("filesystem-touching cases with NO POSIX spelling anywhere — the\n")
        w("POSIX-variant backlog this census pins. basename/dirname are\n")
        w("string-only (no mapper), so their POSIX spellings carry no gap.\n\n")
        if fx:
            n, sensitive = fx
            w("## Fixture-inertness run (native rust side, %d cases)\n\n" % n)
            w("Every case ran twice in the SAME scratch path (wiped between\n")
            w("runs, so cwd-printing commands see one cwd and state cannot\n")
            w("leak across runs): once without and once with the\n")
            w("shell-namespace fixture env (`qc_common.posix_fixture`). The\n")
            w("corpus carries no POSIX spellings, so unexpected diffs would\n")
            w("be fixture leakage. Sensitivities split into two classes:\n")
            w("**expected** — commands whose output legitimately follows the\n")
            w("env (env dumps, TMPDIR consumers, volume enumeration) — and\n")
            w("**unexpected**, which need a look before trusting any\n")
            w("posix-round verdict.\n\n")
            expected_cmds = {
                # full-env dumps: the fixture vars are SUPPOSED to show up
                "printenv",
                # TMPDIR consumers: default template dir moves with the fixture
                "mktemp",
                # -a table includes path-conf entries derived from the env
                "getconf",
                # volume enumeration follows temp/mount points
                "df",
            }
            unexpected = [s for s in sensitive if s[0] not in expected_cmds]
            w("**%d fixture-sensitive cases, %d unexpected.**\n\n"
              % (len(sensitive), len(unexpected)))
            if sensitive:
                w("| class | command | case | rc without->with | stdout differs |\n")
                w("|---|---|---|---|---|\n")
                for (cmd, cid, base, wfx) in sensitive:
                    cls = ("expected-env" if cmd in expected_cmds
                           else "UNEXPECTED")
                    w("| %s | %s | %s | %s->%s | %s |\n" % (
                        cls, cmd, cid, base[0], wfx[0],
                        "yes" if base[1] != wfx[1] else "no"))
            else:
                w("No fixture-sensitive cases: the fixture is inert on this\n")
                w("corpus (expected — all operands are Windows-form or relative).\n")
            w("\n")


def posix_cmds_tbl(rows):
    return [r for r in rows if r[7] == "yes"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fixture-run", action="store_true",
                    help="also run the corpus twice (fixture inertness leg)")
    args = ap.parse_args()

    rows, total, posix_shaped, fs_cases, gap_cases = census()
    fx = fixture_run() if args.fixture_run else None
    write_report(rows, total, posix_shaped, fs_cases, gap_cases, fx)

    print("census: %d cases, %d path-shaped, %d posix-spelled, "
          "%d FS-touching, %d missing posix variant"
          % (total, sum(r[2] for r in rows), posix_shaped, fs_cases, gap_cases))
    if fx:
        print("fixture-run: %d cases, %d fixture-sensitive" % (fx[0], len(fx[1])))
    print("wrote %s" % OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
