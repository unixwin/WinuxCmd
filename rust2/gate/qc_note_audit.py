#!/usr/bin/env python3
"""gate/qc_note_audit.py — note-class spot-check for the differential gate (#1488).

`note` cases are record-only: they never gate. That made them a blind spot —
the `false --help` pilot bug (issue #1550) survived inside a note row until a
human compared against GNU during wiring. This tool ends indefinite immunity:

  1. inventory   — every note-mode row in gate/cases/*.tsv, with the expected
                   deviation from gate/note-registry.tsv (undocumented notes
                   are themselves a finding).
  2. GNU re-check — each note case is re-run against all three sides (GNU
                   oracle via WSL, Rust driver, C++ dispatcher) and the
                   verdict is computed:
      UPGRADE-STRICT  rust rc+stdout == GNU  → the note can gate again as
                      strict; the C++ deviation stays recorded via r=c:no.
      UPGRADE-EXIT    rust rc == GNU but stdout differs (platform-form-bound)
                      → upgrade to exit.
      MASKED-DIVERGENCE rust != GNU → the note is masking a live pilot
                      divergence (the #1550 class) — command lane must fix
                      it or re-justify the registered deviation.
      HOLD            premise intact and no upgrade path (rare).

Run:  python gate/qc_note_audit.py            # writes gate/NOTE-QC.md
Requires RUST_BIN/CPP_BIN when the worktree default paths are not built.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import qc_common as q  # noqa: E402

REGISTRY = os.path.join(q.GATE_DIR, "note-registry.tsv")
OUT = os.path.join(q.GATE_DIR, "NOTE-QC.md")


def load_registry():
    reg = {}
    if os.path.isfile(REGISTRY):
        with open(REGISTRY, "r", encoding="utf-8") as fh:
            for line in fh:
                line = line.rstrip("\n")
                if not line or line.startswith("#"):
                    continue
                parts = line.split("\t")
                if len(parts) >= 3:
                    reg[(parts[0], parts[1])] = parts[2]
    return reg


def sides_equal_rc_out(a, b):
    return a.rc == b.rc and a.stdout == b.stdout


def classify(g, r, c):
    """(verdict, detail) from gnu/rust/cpp SideResults."""
    if g.error or r.error:
        return "PROBE-FAIL", "harness error: gnu=%s rust=%s" % (g.error, r.error)
    rust_eq_gnu = sides_equal_rc_out(g, r)
    cpp_eq_gnu = sides_equal_rc_out(g, c)
    if rust_eq_gnu and cpp_eq_gnu:
        return "UPGRADE-STRICT", "Rust and C++ both byte-match GNU; note premise stale"
    if rust_eq_gnu:
        return "UPGRADE-STRICT", "Rust byte-matches GNU; C++ deviation inherited-not-fixed"
    if g.rc == r.rc and g.error == "" and r.stdout != g.stdout:
        return "UPGRADE-EXIT", "rc matches GNU, stdout platform-form-bound"
    return (
        "MASKED-DIVERGENCE",
        "Rust diverges from GNU under a note (rc g/r/c=%s/%s/%s)"
        % (g.rc, r.rc, c.rc),
    )


def main():
    reg = load_registry()
    notes = []
    for cmd in q.list_commands():
        for case in q.parse_cases(cmd):
            if case.mode == "note":
                notes.append(case)
    if not notes:
        print("no note-mode cases found")
        return 0

    rows = []
    for case in notes:
        desc = reg.get((case.cmd, case.cid))
        g = q.run_side("gnu", case)
        r = q.run_side("rust", case)
        c = q.run_side("cpp", case)
        verdict, detail = classify(g, r, c)
        rows.append((case, desc, g, r, c, verdict, detail))
        print("%-8s %-24s %-15s %s" % (case.cmd, case.cid, verdict, detail))

    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        w = fh.write
        w("# Gate note-class QC — NOTE-QC.md\n\n")
        w("Notes are record-only rows (`mode = note`) and never gate. This\n")
        w("report is their standing audit: what each note claims, what GNU\n")
        w("actually does today, and whether the note still earns its\n")
        w("immunity. Generated by `python gate/qc_note_audit.py` (GNU probe\n")
        w("via WSL coreutils %s-oracle scratch `/tmp/winuxcmd-gate-qc`);\n" % "9.4")
        w("re-run after any command-lane change touching a noted behavior.\n\n")
        w("Driver provenance: `%s`\n\n" % q.provenance())
        w("Lesson baked in (#1550): `false --help` returning 0 lived inside a\n")
        w("note row until manual wiring checks caught it. A note is not a\n")
        w("verdict; it is a debt with an audit date.\n\n")
        w("Verdicts: **UPGRADE-STRICT/EXIT** = Rust already matches GNU, the\n")
        w("row should gate again (promotion owned by the command lane);\n")
        w("**MASKED-DIVERGENCE** = the note masks a live Rust-vs-GNU\n")
        w("divergence — the exact #1550 failure class, fix it or re-justify\n")
        w("the registered deviation; **UNDOCUMENTED** = no registry entry in\n")
        w("`gate/note-registry.tsv`.\n\n")

        w("## Note inventory + GNU probe re-check\n\n")
        w("| command | case | rc (gnu/rust/cpp) | stdout sha (gnu/rust/cpp) | verdict | finding |\n")
        w("|---|---|---|---|---|---|\n")
        upgrades, violations, undocumented = [], [], []
        for case, desc, g, r, c, verdict, detail in rows:
            w("| %s | %s | %s/%s/%s | %s/%s/%s | %s | %s |\n" % (
                case.cmd, case.cid, g.rc, r.rc, c.rc,
                g.out_sha, r.out_sha, c.out_sha, verdict, detail))
            if verdict.startswith("UPGRADE"):
                upgrades.append((case.cmd, case.cid, verdict, detail))
            elif verdict == "MASKED-DIVERGENCE":
                violations.append((case.cmd, case.cid, detail))
            if desc is None:
                undocumented.append((case.cmd, case.cid))

        w("\n## Expected-deviation registry\n\n")
        w("| command | case | expected deviation (gate/note-registry.tsv) |\n")
        w("|---|---|---|\n")
        for case, desc, *_ in rows:
            w("| %s | %s | %s |\n" % (
                case.cmd, case.cid, desc or "**UNDOCUMENTED**"))

        w("\n## Upgrade candidates (decision owned by the command lane)\n\n")
        if upgrades:
            for cmd, cid, v, d in upgrades:
                w("- `%s/%s` — %s: %s\n" % (cmd, cid, v, d))
        else:
            w("- none this sweep\n")

        w("\n## Masked divergences (note hiding Rust != GNU — #1550 class)\n\n")
        if violations:
            for cmd, cid, d in violations:
                w("- `%s/%s` — %s\n" % (cmd, cid, d))
        else:
            w("- none this sweep\n")

        if undocumented:
            w("\n## Undocumented notes\n\n")
            for cmd, cid in undocumented:
                w("- `%s/%s` has no `gate/note-registry.tsv` entry — add the\n"
                  "  expected deviation before the next sweep.\n" % (cmd, cid))

        w("\n## Per-case evidence (stdout, escaped, first 60 bytes)\n\n")
        for case, desc, g, r, c, verdict, detail in rows:
            w("- **%s/%s** (%s)\n" % (case.cmd, case.cid, verdict))
            w("  - args: `%s` stdin: `%s`\n" % (" ".join(case.args), case.stdin))
            if desc:
                w("  - claimed: %s\n" % desc)
            for name, s in (("gnu", g), ("rust", r), ("cpp", c)):
                w("  - %s: rc=%s out=`%s`%s\n" % (
                    name, s.rc, s.out_repr(), (" ERR:" + s.error) if s.error else ""))
        w("\n## Re-run\n\n")
        w("```sh\n")
        w("# RUST_BIN/CPP_BIN default to this worktree's builds; the wave2\n")
        w("# RUST_BIN_W2 split is retired (everything is wired to main).\n")
        w("python gate/qc_note_audit.py   # regenerates gate/NOTE-QC.md\n")
        w("```\n")

    print("\nwrote %s" % OUT)
    print("upgrade candidates: %d, masked divergences: %d, undocumented: %d"
          % (len(upgrades), len(violations), len(undocumented)))
    return 1 if violations else 0


if __name__ == "__main__":
    sys.exit(main())
