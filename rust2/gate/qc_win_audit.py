#!/usr/bin/env python3
"""gate/qc_win_audit.py — win-class output audit for the differential gate (#1488).

`win` cases gate only Rust-vs-C++ exit status; their stdout is recorded but
NEVER compared anywhere. That makes win a black hole: 100+ rows whose bytes
nobody looks at. This audit diffs those bytes.

For every win-mode row: run the Rust driver and the C++ dispatcher, compare
stdout (rc is already gated by run-gate.sh) and classify the difference:

  aligned      byte-equal stdout.
  wording      equal after normalization (line endings, path separators,
               drive-letter case, whitespace runs, product brand tokens).
               Same structure, different text — a candidate for demotion to
               `note` or for a normalization rule, decided by the command
               lane.
  structural   still different after normalization — layout/content differ;
               needs human eyes.

Run:  python gate/qc_win_audit.py            # writes gate/WIN-AUDIT.md
Requires RUST_BIN/CPP_BIN when the worktree default paths are not built.
"""

import difflib
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import qc_common as q  # noqa: E402

OUT = os.path.join(q.GATE_DIR, "WIN-AUDIT.md")

BRAND_TOKENS = re.compile(
    r"\((?:winuxcmd|gnu coreutils|coreutils)\)|winuxcmd|gnu coreutils", re.I
)


def normalize(b):
    s = b.decode("utf-8", "replace")
    s = s.replace("\r\n", "\n").replace("\r", "\n")
    s = s.replace("\\", "/")
    s = re.sub(r"([A-Za-z]):/", lambda m: m.group(1).lower() + ":/", s)
    s = BRAND_TOKENS.sub("", s)
    s = "\n".join(line.rstrip() for line in s.split("\n"))
    s = re.sub(r"[ \t]+", " ", s)
    return s.strip()


def classify(r, c):
    if r.error or c.error:
        return "PROBE-FAIL", "harness error: rust=%s cpp=%s" % (r.error, c.error)
    if r.stdout == c.stdout:
        return "ALIGNED", ""
    rn, cn = normalize(r.stdout), normalize(c.stdout)
    if rn == cn:
        return "WORDING", "equal after normalization (brand/path/case/space)"
    rt, ct = rn.split(), cn.split()
    if sorted(rt) == sorted(ct):
        return "WORDING", "same token multiset, order differs"
    return "STRUCTURAL", "%d vs %d normalized lines" % (
        len(rn.splitlines()) or 1, len(cn.splitlines()) or 1)


def diff_excerpt(r, c, limit=14):
    rl = normalize(r.stdout).splitlines()
    cl = normalize(c.stdout).splitlines()
    out = []
    for line in difflib.unified_diff(cl, rl, "cpp", "rust", lineterm="", n=0):
        out.append(line)
    return out[:limit]


def main():
    wins = []
    for cmd in q.list_commands():
        for case in q.parse_cases(cmd):
            if case.mode == "win":
                wins.append(case)
    if not wins:
        print("no win-mode cases found")
        return 0

    rows = []
    by_cmd = {}
    for case in wins:
        r = q.run_side("rust", case)
        c = q.run_side("cpp", case)
        verdict, detail = classify(r, c)
        rows.append((case, r, c, verdict, detail))
        by_cmd.setdefault(case.cmd, {"ALIGNED": 0, "WORDING": 0, "STRUCTURAL": 0,
                                     "PROBE-FAIL": 0, "n": 0})
        by_cmd[case.cmd][verdict] += 1
        by_cmd[case.cmd]["n"] += 1
        print("%-10s %-26s %-11s %s" % (case.cmd, case.cid, verdict, detail))

    total = len(rows)
    nword = sum(1 for x in rows if x[3] == "WORDING")
    nstruct = sum(1 for x in rows if x[3] == "STRUCTURAL")
    nalign = sum(1 for x in rows if x[3] == "ALIGNED")
    nfail = sum(1 for x in rows if x[3] == "PROBE-FAIL")

    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        w = fh.write
        w("# Gate win-class audit — WIN-AUDIT.md\n\n")
        w("`win` cases gate only Rust-vs-C++ exit status; stdout is recorded\n")
        w("but never compared anywhere in the gate. This audit diffs those\n")
        w("bytes so the win class cannot become a silent black hole.\n")
        w("Generated by `python gate/qc_win_audit.py`; re-run after any\n")
        w("command-lane change to a win-heavy command.\n\n")
        w("Classifications: **aligned** (byte-equal), **wording** (equal after\n")
        w("normalizing brand/path/line-ending/whitespace — demote-to-note\n")
        w("candidates for the command lane), **structural** (normalized bodies\n")
        w("still differ — human review), **probe-fail** (harness error).\n\n")
        w("Driver provenance: `%s`\n\n" % q.provenance())
        w("## Per-command summary\n\n")
        w("| command | win cases | aligned | wording | structural | probe-fail |\n")
        w("|---|---|---|---|---|---|\n")
        for cmd in sorted(by_cmd):
            d = by_cmd[cmd]
            w("| %s | %d | %d | %d | %d | %d |\n" % (
                cmd, d["n"], d["ALIGNED"], d["WORDING"], d["STRUCTURAL"],
                d["PROBE-FAIL"]))
        w("| **total** | **%d** | **%d** | **%d** | **%d** | **%d** |\n" % (
            total, nalign, nword, nstruct, nfail))

        w("\n## Wording-only differences (structure equal, text differs)\n\n")
        w("Same shape after normalization — likely pure wording. Each is a\n")
        w("candidate for a `note` demotion or an explicit normalization rule;\n")
        w("decisions belong to the command lane.\n\n")
        any_word = False
        for case, r, c, verdict, detail in rows:
            if verdict != "WORDING":
                continue
            any_word = True
            w("- **%s/%s** — %s\n" % (case.cmd, case.cid, detail))
            w("  - rust: `%s`\n" % r.out_repr(70))
            w("  - cpp:  `%s`\n" % c.out_repr(70))
        if not any_word:
            w("- none this sweep\n")

        w("\n## Structural differences (needs human review)\n\n")
        any_s = False
        for case, r, c, verdict, detail in rows:
            if verdict != "STRUCTURAL":
                continue
            any_s = True
            w("- **%s/%s** — %s\n" % (case.cmd, case.cid, detail))
            for line in diff_excerpt(r, c):
                w("  - `%s`\n" % line)
        if not any_s:
            w("- none this sweep\n")

        if nfail:
            w("\n## Probe failures\n\n")
            for case, r, c, verdict, detail in rows:
                if verdict == "PROBE-FAIL":
                    w("- **%s/%s** — %s\n" % (case.cmd, case.cid, detail))

        w("\n## Re-run\n\n")
        w("```sh\n")
        w("RUST_BIN=.../main/winuxcmd-driver.exe \\\n")
        w("RUST_BIN_W2=.../wave2/winuxcmd-driver.exe \\\n")
        w("CPP_BIN=.../winuxcmd.exe \\\n")
        w("  python gate/qc_win_audit.py   # regenerates gate/WIN-AUDIT.md\n")
        w("```\n")

    print("\nwrote %s" % OUT)
    print("aligned=%d wording=%d structural=%d probe-fail=%d (of %d win cases)"
          % (nalign, nword, nstruct, nfail, total))
    return 0


if __name__ == "__main__":
    sys.exit(main())
