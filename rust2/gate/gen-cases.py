def _load_ledger():
    """Parse target/gate/ledger.tsv rows into dicts (empty list if absent)."""
    rows = []
    if not os.path.isfile(LEDGER):
        return rows
    with open(LEDGER, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if not line:
                continue
            f = line.split("|")
            if len(f) < 6:
                continue
            rcs = f[3].split("=", 1)[-1].split("/")  # r/g/c
            out = f[4]  # out(r=g:yes r=c:no)
            rows.append({
                "cmd": f[0], "id": f[1], "mode": f[2],
                "r_rc": rcs[0] if len(rcs) > 0 else "?",
                "g_rc": rcs[1] if len(rcs) > 1 else "?",
                "c_rc": rcs[2] if len(rcs) > 2 else "?",
                "g_out_eq": "r=g:yes" in out,
                "c_eq": "r=c:yes" in out,
                "note": f[5] if len(f) > 5 else "",
            })
    return rows


def _ledger_verdict(lr):
    """Recompute a ledger row's gate verdict from its recorded comparisons."""
    if lr["mode"] == "strict":
        ok = lr["g_out_eq"] and lr["r_rc"] == lr["g_rc"]
    elif lr["mode"] == "exit":
        ok = lr["r_rc"] == lr["g_rc"]
    elif lr["mode"] == "win":
        ok = lr["r_rc"] == lr["c_rc"]
    else:  # note / bad-mode
        ok = lr["mode"] == "note"
    return "ok" if ok else "FAIL"


def _is_vacuous(lr):
    """Vacuous-green: strict/exit rows where BOTH compared sides are
    command-not-found (rc 127) — the gate compares two failures and passes
    (empty stdout == empty stdout, so the byte check is vacuously true too).
    The bracket family shipped like this for weeks."""
    if lr["mode"] not in ("strict", "exit"):
        return False
    return lr["r_rc"] == "127" and lr["g_rc"] == "127" and lr["g_out_eq"]


def cmd_coverage(rows):
    modes = {}
    for r in rows:
        modes[r[1]] = modes.get(r[1], 0) + 1
    total = len(rows)
    gated = modes.get("strict", 0) + modes.get("exit", 0)
    return {
        "total": total, "modes": modes, "gated": gated,
        "gnu_ratio": (gated / total) if total else 0.0,
    }


def do_coverage():
    ledger = _load_ledger()
    by_cmd_ledger = {}
    for lr in ledger:
        by_cmd_ledger.setdefault(lr["cmd"], []).append(lr)

    out_path = os.path.join(HERE, "COVERAGE.md")
    lines = [
        "# Gate coverage dashboard — COVERAGE.md",
        "",
        "Generated by `python gate/gen-cases.py --coverage` (no case data is",
        "read from the TSVs — counts come from the `gen-cases.py` definitions,",
        "which are the single source of truth). C++ parity, gate verdicts and",
        "vacuous-green detection come from `target/gate/ledger.tsv` (the last",
        "`bash gate/run-gate.sh` run).",
        "",
        "Columns:",
        "",
        "- **GNU direct** — strict+exit rows, the share of cases whose stdout",
        "  bytes AND exit status are gated against GNU byte-for-byte.",
        "- **C++ parity** — ledger rows byte/rc-equal on the Rust and C++",
        "  sides (`r=c:yes`); divergence is recorded, not gated.",
        "- **vacuous** — strict/exit rows that passed because BOTH sides were",
        "  command-not-found (rc 127, empty stdout). A vacuous row tests",
        "  nothing; every one is a gate-mechanism bug (see the bracket",
        "  family, fixed 2026-11-10 in run-gate.sh).",
        "",
    ]
    if not ledger:
        lines += [
            "No ledger found (`target/gate/ledger.tsv`) — parity/verdict/vacuous",
            "columns omitted. Run `bash gate/run-gate.sh` first.",
            "",
        ]
    lines += [
        "| command | cases | strict | exit | win | note | GNU direct | C++ parity | gate | vacuous |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    stats = []
    for cmd, rows in collect():
        cov = cmd_coverage(rows)
        lrows = by_cmd_ledger.get(cmd, [])
        cpy = sum(1 for lr in lrows if lr["c_eq"])
        fails = sum(1 for lr in lrows if _ledger_verdict(lr) == "FAIL")
        vac = sum(1 for lr in lrows if _is_vacuous(lr))
        gate = ("GREEN" if fails == 0 else "%d FAIL" % fails) if lrows else "-"
        parity = ("%d/%d" % (cpy, len(lrows))) if lrows else "-"
        vac_s = str(vac) if lrows else "-"
        lines.append("| %s | %d | %d | %d | %d | %d | %d%% | %s | %s | %s |" % (
            cmd, cov["total"], cov["modes"].get("strict", 0),
            cov["modes"].get("exit", 0), cov["modes"].get("win", 0),
            cov["modes"].get("note", 0), round(100 * cov["gnu_ratio"]),
            parity, gate, vac_s))
        stats.append((cmd, cov, bool(lrows)))

    tot = sum(c["total"] for _, c, _ in stats)
    tg = sum(c["gated"] for _, c, _ in stats)
    tnote = sum(c["modes"].get("note", 0) for _, c, _ in stats)
    lall = ledger
    tcpy = sum(1 for lr in lall if lr["c_eq"])
    tvac = sum(1 for lr in lall if _is_vacuous(lr))
    tfail = sum(1 for lr in lall if _ledger_verdict(lr) == "FAIL")
    lines.append("| **total** | **%d** | | | | %d | **%d%%** | %s | %s | %s |" % (
        tot, tnote, round(100 * tg / tot) if tot else 0,
        ("%d/%d" % (tcpy, len(lall))) if lall else "-",
        ("GREEN" if tfail == 0 else "%d FAIL" % tfail) if lall else "-",
        str(tvac) if lall else "-"))

    worst = sorted((s for s in stats), key=lambda s: s[1]["gnu_ratio"])[:5]
    lines += ["", "## Worst 5 by GNU-direct ratio", ""]
    for cmd, cov, _ in worst:
        lines.append("- **%s** — %d%% GNU-direct (%d/%d; win-heavy value-model"
                     " command)" % (cmd, round(100 * cov["gnu_ratio"]),
                                    cov["gated"], cov["total"]))
    lines += [
        "",
        "GNU-direct is expected low for Windows value-model commands",
        "(whoami/uname/id/hostname/getconf/pwd/df): their success output is",
        "platform-inherent and gated Rust-vs-C++ instead. The dangerous",
        "direction is GNU-direct falling on byte-platform-independent",
        "commands (digests, encoders) — that is where a dropped `strict`",
        "hides.",
        "",
    ]
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote %s (%d commands, %d cases)" % (out_path, len(stats), tot))
    return 0


