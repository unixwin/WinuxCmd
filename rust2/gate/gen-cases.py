def do_dup_check():
    """Warn on cases with identical (args, stdin, env, setup).

    - intra-command exact duplicates are redundant rows (WARN, exit 1);
    - cross-command shared keys are expected when two commands mirror a
      matrix by design (true/false, the digest family, basename/dirname);
      those are reported as families (>=50% key overlap);
    - other cross-command pairs with >=5 shared keys are listed for
      copy-paste review; 1-4 shared keys is inherent template overlap
      (every command has plain/extra/--bogus/--help rows) and only counted.
    """
    fam_warn = []
    intra = []
    key_cmds = {}
    for cmd, rows in collect():
        seen = {}
        for r in rows:
            key = (tuple(r[5]), r[4], r[3], r[2])
            seen.setdefault(key, []).append(r[0])
            key_cmds.setdefault(key, []).append(cmd)
        for key, ids in sorted(seen.items()):
            if len(ids) > 1:
                intra.append((cmd, ids, key))
    # cross-command overlap matrix
    import collections
    cmd_keys = collections.defaultdict(set)
    for key, cmds in key_cmds.items():
        for c in cmds:
            cmd_keys[c].add(key)
    fams = []
    review = []
    trivial = 0
    cmds = sorted(cmd_keys)
    for i, a in enumerate(cmds):
        for b in cmds[i + 1:]:
            inter = cmd_keys[a] & cmd_keys[b]
            if not inter:
                continue
            smaller = min(len(cmd_keys[a]), len(cmd_keys[b]))
            if smaller and len(inter) / smaller >= 0.5:
                fams.append((a, b, len(inter), smaller))
            elif len(inter) >= 5:
                review.append((a, b, len(inter)))
            else:
                # 1-4 shared keys between unrelated commands is inherent to
                # the template-based suite (plain/extra/--bogus/--help rows);
                # counted, not listed.
                trivial += 1
    print("intra-command duplicate cases: %d" % len(intra))
    for cmd, ids, key in intra:
        print("  WARN %s: %s share args=%r stdin=%r env=%r setup=%r"
              % (cmd, "+".join(ids), key[0], key[1], key[2], key[3]))
    print("shared matrix families (>=50%% key overlap, by design): %d" % len(fams))
    for a, b, n, s in fams:
        print("  %s <-> %s: %d shared keys (%d%%)" % (a, b, n, round(100 * n / s)))
    print("cross-command pairs with >=5 shared keys (review for copy-paste): %d"
          % len(review))
    for a, b, n in sorted(review, key=lambda x: -x[2]):
        print("  REVIEW %s <-> %s: %d shared keys" % (a, b, n))
    print("template overlap (1-4 shared keys, informational): %d pairs" % trivial)
    print("findings: %d (exit %d)" % (len(intra), 1 if intra else 0))
    return 1 if intra else 0

if __name__ == "__main__":

    if "--coverage" in sys.argv:
        sys.exit(do_coverage())
    if "--dup-check" in sys.argv:
        sys.exit(do_dup_check())

