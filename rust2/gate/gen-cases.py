#!/usr/bin/env python3
"""Generate gate/cases/<cmd>.tsv from explicit case tuples.

Tab-separated case tables hand-edited in an editor silently mis-align; this
generator is the single source of truth. Case tuple:

    (id, mode, setup, env, stdin, [args...])

mode: strict | exit | win   (see run-gate.sh header)
env : comma-separated K=V assignments
args: "@EMPTY@" encodes a literal empty-string argument (handled by harness)

Run from anywhere: python gate/gen-cases.py
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
CASES_DIR = os.path.join(HERE, "cases")


def emit(name, rows):
    path = os.path.join(CASES_DIR, name + ".tsv")
    lines = [
        "# generated by gate/gen-cases.py — do not hand-edit tab columns",
        "# id<TAB>mode<TAB>setup<TAB>env<TAB>stdin<TAB>args... (@EMPTY@ = empty arg)",
    ]
    for r in rows:
        cid, mode, setup, env, stdin = r[:5]
        args = r[5]
        fields = [cid, mode, setup, env, stdin] + list(args)
        lines.append("\t".join(fields))
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {path} ({len(rows)} cases)")


