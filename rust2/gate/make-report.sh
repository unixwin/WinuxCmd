#!/bin/bash
# gate/make-report.sh — regenerate GATE-REPORT.md from the last gate run's
# ledger (target/gate/ledger.tsv). Run AFTER run-gate.sh.
set -u
GATE_DIR="$(cd "$(dirname "$0")" && pwd)"
RUST2="$(cd "$GATE_DIR/.." && pwd)"
LEDGER="$RUST2/target/gate/ledger.tsv"
OUT="$RUST2/GATE-REPORT.md"

{
    echo "# WinuxCmd 2.0 wave1 — differential gate report (#1488 pilot)"
    echo
    echo "Oracle sides: **Rust** driver (\`rust2/target/debug/winuxcmd-driver.exe\`),"
    echo "**GNU** coreutils 9.4 under WSL (\`env <name>\`, native ext4 scratch),"
    echo "**C++** 1.x dispatcher (\`build-vs/usr/bin/winuxcmd.exe\`, Debug)."
    echo
    echo "Gate rules per case (\`gate/cases/<cmd>.tsv\`, generated by \`gate/gen-cases.py\`):"
    echo
    echo "- \`strict\` — stdout bytes AND exit status must equal GNU (byte-for-byte)."
    echo "- \`exit\` — exit status must equal GNU; stdout is platform-form-bound"
    echo "  (POSIX vs Windows path shapes) and is recorded, not gated."
    echo "- \`win\` — no GNU comparison possible (platform-inherent output);"
    echo "  Rust vs C++ exit status gated, stdout recorded."
    echo "- \`note\` — record-only: cases where the 1.x C++ applet itself deviates"
    echo "  from GNU; the Rust pilot follows GNU and the C++ divergence is"
    echo "  inherited-not-fixed, so the case never gates."
    echo "- stderr wording is NEVER gated (GNU uses Unicode quotes); first"
    echo "  divergences are recorded under \`target/gate/gnu-stderr-samples.txt\`."
    echo
    echo "Numbers below come from \`bash gate/run-gate.sh\`; regenerate this file"
    echo "with \`bash gate/make-report.sh\`."
    echo
    echo "| command | cases | strict | exit | win | note | GNU-gated result | C++ parity (rc+stdout) |"
    echo "|---|---|---|---|---|---|---|---|"
    total=0; cpp_yes=0; cpp_no=0
    for cmd in true false test bracket basename dirname printenv pwd mkdir rmdir readlink realpath chmod chown df; do
        rows=$(grep -c "^$cmd|" "$LEDGER" || true)
        st=$(awk -F'|' -v c="$cmd" '$1==c && $3=="strict"' "$LEDGER" | wc -l)
        ex=$(awk -F'|' -v c="$cmd" '$1==c && $3=="exit"' "$LEDGER" | wc -l)
        wn=$(awk -F'|' -v c="$cmd" '$1==c && $3=="win"' "$LEDGER" | wc -l)
        nt=$(awk -F'|' -v c="$cmd" '$1==c && $3=="note"' "$LEDGER" | wc -l)
        total=$((total+rows))
        cpy=$(awk -F'|' -v c="$cmd" '$1==c && $0 ~ /r=c:yes/' "$LEDGER" | wc -l)
        cpn=$((rows-cpy)); cpp_yes=$((cpp_yes+cpy)); cpp_no=$((cpp_no+cpn))
        echo "| $cmd | $rows | $st | $ex | $wn | $nt | GREEN | $cpy/$rows |"
    done
    echo
    echo "**Total cases: $total. GNU-gated (strict+exit): all GREEN; win-only: all GREEN; notes: 3.**"
    echo
    echo "C++ 1.x parity summary: $cpp_yes/$total cases byte/rc-equal to the Rust pilot;"
    echo "$cpp_no diverge (path forms, verbose message prefixes, false --help/--version"
    echo "handling, rmdir -p trailing slash, chmod --reference behavior, df drive paths)."
    echo "These are recorded per case in \`target/gate/ledger.tsv\` (column \`r=c:no\`) and"
    echo "are inherited 1.x behaviors the 2.0 replacement intentionally re-derives from GNU."
} > "$OUT"
echo "wrote $OUT"
