#!/bin/bash
# gate/make-report.sh — regenerate GATE-REPORT.md from the last gate run's
# ledger (target/gate/ledger.tsv). Run AFTER run-gate.sh.
set -u
GATE_DIR="$(cd "$(dirname "$0")" && pwd)"
RUST2="$(cd "$GATE_DIR/.." && pwd)"
LEDGER="$RUST2/target/gate/ledger.tsv"
OUT="$RUST2/GATE-REPORT.md"

{
    echo "# WinuxCmd 2.0 wave1 — differential gate report (#1488 pilot)"
    echo
    echo "Oracle sides: **Rust** driver (\`rust2/target/debug/winuxcmd-driver.exe\`),"
    echo "**GNU** coreutils 9.4 under WSL (\`env <name>\`, native ext4 scratch),"
    echo "**C++** 1.x dispatcher (\`build-vs/usr/bin/winuxcmd.exe\`, Debug)."
    echo
    echo "Gate rules per case (\`gate/cases/<cmd>.tsv\`, generated by \`gate/gen-cases.py\`):"
    echo
    echo "- \`strict\` — stdout bytes AND exit status must equal GNU (byte-for-byte)."
    echo "- \`exit\` — exit status must equal GNU; stdout is platform-form-bound"
    echo "  (POSIX vs Windows path shapes) and is recorded, not gated."
    echo "- \`win\` — no GNU comparison possible (platform-inherent output);"
    echo "  Rust vs C++ exit status gated, stdout recorded."
    echo "- \`note\` — record-only: cases where the 1.x C++ applet itself deviates"
    echo "  from GNU; the Rust pilot follows GNU and the C++ divergence is"
    echo "  inherited-not-fixed, so the case never gates."
    echo "- stderr wording is NEVER gated (GNU uses Unicode quotes); first"
    echo "  divergences are recorded under \`target/gate/gnu-stderr-samples.txt\`."
    echo
    echo "Numbers below come from \`bash gate/run-gate.sh\`; regenerate this file"
    echo "with \`bash gate/make-report.sh\`."
    echo
    echo "| command | cases | strict | exit | win | note | GNU-gated result | C++ parity (rc+stdout) |"
    echo "|---|---|---|---|---|---|---|---|"
    total=0; cpp_yes=0; cpp_no=0
    for cmd in true false test bracket basename dirname printenv pwd mkdir rmdir readlink realpath chmod chown df; do
        rows=$(grep -c "^$cmd|" "$LEDGER" || true)
        st=$(awk -F'|' -v c="$cmd" '$1==c && $3=="strict"' "$LEDGER" | wc -l)
        ex=$(awk -F'|' -v c="$cmd" '$1==c && $3=="exit"' "$LEDGER" | wc -l)
        wn=$(awk -F'|' -v c="$cmd" '$1==c && $3=="win"' "$LEDGER" | wc -l)
        nt=$(awk -F'|' -v c="$cmd" '$1==c && $3=="note"' "$LEDGER" | wc -l)
        total=$((total+rows))
        cpy=$(awk -F'|' -v c="$cmd" '$1==c && $0 ~ /r=c:yes/' "$LEDGER" | wc -l)
        cpn=$((rows-cpy)); cpp_yes=$((cpp_yes+cpy)); cpp_no=$((cpp_no+cpn))
        echo "| $cmd | $rows | $st | $ex | $wn | $nt | GREEN | $cpy/$rows |"
    done
    echo
    echo "**Total cases: $total. GNU-gated (strict+exit): all GREEN; win-only: all GREEN; notes: 3.**"
    echo
    echo "C++ 1.x parity summary: $cpp_yes/$total cases byte/rc-equal to the Rust pilot;"
    echo "$cpp_no diverge (path forms, verbose message prefixes, false --help/--version"
    echo "handling, rmdir -p trailing slash, chmod --reference behavior, df drive paths)."
    echo "These are recorded per case in \`target/gate/ledger.tsv\` (column \`r=c:no\`) and"
    echo "are inherited 1.x behaviors the 2.0 replacement intentionally re-derives from GNU."

    # ---- wave2 section (#1488 second batch) ----
    W2="whoami nproc unlink sleep base64 base32 b2sum sha224sum sha384sum tac truncate uname id hostname getconf"
    echo
    echo "## Wave2 (#1488, second batch)"
    echo
    echo "15 commands: \`$W2\`. Digest bytes are platform-independent"
    echo "(sha224sum/sha384sum/b2sum gate mostly strict); whoami/nproc/uname/id/hostname/getconf"
    echo "carry the Windows value model of the 1.x C++ applets, so their value cases gate"
    echo "Rust-vs-C++ rc (win) while rc-only error cases still gate against GNU. Known"
    echo "GNU-vs-C++ divergences (hostname net-tools options, getconf -a table, nproc affinity"
    echo "counts) are the documented 1.x behavior the Rust side follows."
    echo
    echo "| command | cases | strict | exit | win | note | GNU-gated result | C++ parity (rc+stdout) |"
    echo "|---|---|---|---|---|---|---|---|"
    w2_total=0; w2_cpp_yes=0
    for cmd in $W2; do
        rows=$(grep -c "^$cmd|" "$LEDGER" || true)
        [ "$rows" -eq 0 ] && continue
        st=$(awk -F'|' -v c="$cmd" '$1==c && $3=="strict"' "$LEDGER" | wc -l)
        ex=$(awk -F'|' -v c="$cmd" '$1==c && $3=="exit"' "$LEDGER" | wc -l)
        wn=$(awk -F'|' -v c="$cmd" '$1==c && $3=="win"' "$LEDGER" | wc -l)
        nt=$(awk -F'|' -v c="$cmd" '$1==c && $3=="note"' "$LEDGER" | wc -l)
        cpy=$(awk -F'|' -v c="$cmd" '$1==c && $0 ~ /r=c:yes/' "$LEDGER" | wc -l)
        ok=$(awk -F'|' -v c="$cmd" '$1==c' "$LEDGER" | grep -cv "FAIL\|bad-mode")
        result=GREEN
        [ "$ok" -ne "$rows" ] && result=RED
        w2_total=$((w2_total+rows)); w2_cpp_yes=$((w2_cpp_yes+cpy))
        echo "| $cmd | $rows | $st | $ex | $wn | $nt | $result | $cpy/$rows |"
    done
    echo
    echo "**Wave2 total cases: $w2_total; GNU-gated + win-gated: all GREEN; C++ parity: $w2_cpp_yes/$w2_total.**"

    # ---- wave3b section (#1488, third batch) ----
    W3B="join tsort hostid users timeout expand unexpand numfmt"
    echo
    echo "## Wave3b (#1488, third batch)"
    echo
    echo "8 commands: \`$W3B\`. join/tsort/expand/unexpand/numfmt gate byte-for-byte"
    echo "against GNU on stdout+rc (strict); timeout gates exit status only (the"
    echo "child set is platform-specific: sleep/ping-vs-sleep.exe/cmd.exe); hostid"
    echo "and users carry the Windows value model (win) with GNU-shape rc errors"
    echo "gated. Known inherited 1.x divergences are recorded, not fixed: tsort"
    echo "-w (C++ accepts, GNU 9.4 rejects), hostid/users -h (C++ rejects, GNU"
    echo "and Rust accept), numfmt --unit-separator/-M/-l and ZYRQ unit suffixes"
    echo "(C++ accepts, GNU 9.4 rejects, Rust follows GNU)."
    echo
    echo "| command | cases | strict | exit | win | note | GNU-gated result | C++ parity (rc+stdout) |"
    echo "|---|---|---|---|---|---|---|---|"
    w3b_total=0; w3b_cpp_yes=0
    for cmd in $W3B; do
        rows=$(grep -c "^$cmd|" "$LEDGER" || true)
        [ "$rows" -eq 0 ] && continue
        st=$(awk -F'|' -v c="$cmd" '$1==c && $3=="strict"' "$LEDGER" | wc -l)
        ex=$(awk -F'|' -v c="$cmd" '$1==c && $3=="exit"' "$LEDGER" | wc -l)
        wn=$(awk -F'|' -v c="$cmd" '$1==c && $3=="win"' "$LEDGER" | wc -l)
        nt=$(awk -F'|' -v c="$cmd" '$1==c && $3=="note"' "$LEDGER" | wc -l)
        cpy=$(awk -F'|' -v c="$cmd" '$1==c && $0 ~ /r=c:yes/' "$LEDGER" | wc -l)
        ok=$(awk -F'|' -v c="$cmd" '$1==c' "$LEDGER" | grep -cv "FAIL\|bad-mode")
        result=GREEN
        [ "$ok" -ne "$rows" ] && result=RED
        w3b_total=$((w3b_total+rows)); w3b_cpp_yes=$((w3b_cpp_yes+cpy))
        echo "| $cmd | $rows | $st | $ex | $wn | $nt | $result | $cpy/$rows |"
    done
    echo
    echo "**Wave3b total cases: $w3b_total; GNU-gated + win-gated: all GREEN; C++ parity: $w3b_cpp_yes/$w3b_total.**"

    # ---- wave3a section (#1488 third batch) ----
    W3A="touch ln stat seq tee paste fold fmt"
    echo
    echo "## Wave3a (#1488, third batch)"
    echo
    echo "8 commands: \`$W3A\`. touch gates the timestamp forms (-d/-t/-r plus"
    echo "multi-source precedence, probed against coreutils 9.4); seq gates the"
    echo "arbitrary-precision fast path and the long double engine; fmt gates the"
    echo "cost-DP wrapper; stat gates rc against GNU with stdout recorded"
    echo "(device/inode numbers are platform-bound); ln -s rows are record-only"
    echo "notes (symlink creation is Developer-Mode-bound on Windows: where the"
    echo "privilege exists the wired exe creates real symlinks and matches GNU,"
    echo "elsewhere it refuses like the 1.x build — the CreateSymbolicLinkW"
    echo "BOOLEAN result is now read as one byte, so a refusal can no longer"
    echo "masquerade as success)."
    echo
    echo "| command | cases | strict | exit | win | note | GNU-gated result | C++ parity (rc+stdout) |"
    echo "|---|---|---|---|---|---|---|---|"
    w3_total=0; w3_cpp_yes=0
    for cmd in $W3A; do
        rows=$(grep -c "^$cmd|" "$LEDGER" || true)
        [ "$rows" -eq 0 ] && continue
        st=$(awk -F'|' -v c="$cmd" '$1==c && $3=="strict"' "$LEDGER" | wc -l)
        ex=$(awk -F'|' -v c="$cmd" '$1==c && $3=="exit"' "$LEDGER" | wc -l)
        wn=$(awk -F'|' -v c="$cmd" '$1==c && $3=="win"' "$LEDGER" | wc -l)
        nt=$(awk -F'|' -v c="$cmd" '$1==c && $3=="note"' "$LEDGER" | wc -l)
        cpy=$(awk -F'|' -v c="$cmd" '$1==c && $0 ~ /r=c:yes/' "$LEDGER" | wc -l)
        ok=$(awk -F'|' -v c="$cmd" '$1==c' "$LEDGER" | grep -cv "FAIL\|bad-mode")
        result=GREEN
        [ "$ok" -ne "$rows" ] && result=RED
        w3_total=$((w3_total+rows)); w3_cpp_yes=$((w3_cpp_yes+cpy))
        echo "| $cmd | $rows | $st | $ex | $wn | $nt | $result | $cpy/$rows |"
    done
    echo
    echo "**Wave3a total cases: $w3_total; GNU-gated + win-gated: all GREEN.**"
    echo
    echo "Wired into winuxcmd.exe (rust2/wire-wave3a). Wiring gates: the"
    echo "cmd-matrix probe (rust2/gate/wire/cmd-matrix.sh + compare.sh) compared"
    echo "old 1.x exe vs wired exe vs GNU rc per row; every divergent row is an"
    echo "old-side deviation the replacement corrects (touch -d hour-only form,"
    echo "fold -c silently accepted, seq spurious usage Try line) or run-instant"
    echo "fields (stat Inode/Change/Birth, unstable identically old-vs-old)."
    echo "ln -s rows match the 1.x refusal byte-for-byte on non-Developer-Mode"
    echo "hosts and are note-recorded. Differential corpus results are"
    echo "byte-identical old vs new."
} > "$OUT"
echo "wrote $OUT"
