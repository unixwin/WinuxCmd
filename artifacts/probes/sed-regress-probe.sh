run r10 -e "s/a/\Lb\E/"
run r11 -e "s/  */ /g"
run r12 -e "N; s/\n/ /"
run r13 -e "s/\$/ END/"
run r14 -e "s/^/START /"
run r15 -e "s/[aeiou]/X/g"
run r16 -e "s/[^aeiou]/X/g"
run r17 -e "y/abc/xyz/"
run r18 -e "1,2 s/a/X/"
run r19 -e "3 s/a/X/"
run r20 -e "\$ s/a/X/"
run r21 -e "/b/ s/a/X/"
run r22 -e "/z/ s/a/X/"
run r23 -e "! s/a/X/"
