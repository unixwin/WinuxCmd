#!/usr/bin/env bash
# sed regression probe (pre-existing non-brace forms). usage: sed-regress-probe.sh <sed-binary> <outdir>
set -u
SEDBIN="$1"
OUT="$2"
mkdir -p "$OUT"
printf "alpha\nbravo\ncarlos\ndelta\n" > "$OUT/in.txt"
printf "rdata\n" > "$OUT/rfile.txt"
run() {
  local id="$1"; shift
  "$SEDBIN" "$@" "$OUT/in.txt" > "$OUT/$id.out" 2> "$OUT/$id.err"
  printf "E=%s\n" "$?" > "$OUT/$id.exit"
}
run r01 -e "s/a/X/"
run r02 -e "s/a/X/g"
